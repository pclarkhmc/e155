int main(void) {
    // Enable clocks
    RCC->AHB2ENR |= (1 << 0);         // GPIOA ON
    RCC->APB2ENR |= (1 << 17);        // TIM16 ON

    // Set pin PA6 to alternate function 14 (TIM16_CH1)
    GPIOA->MODER &= ~(0b11 << 12);    // clear MODE6
    GPIOA->MODER |=  (0b10 << 12);    // MODE6 = 10 (alternate function)

    // Set alternate function to 14
    GPIOA->AFRL  &= ~(0b1111 << 24);  // clear AFSEL6
    GPIOA->AFRL  |=  (14 << 24);      // AFSEL6 = 14

    // Set timer clock to 1M (MSI(4MHz) / (PSC(3) + 1) = 1 MHz
    TIM16->PSC  = 3;
    TIM16->ARR  = 999;   // initial frequency
    TIM16->CCR1 = 0;     // inital duty cycle

    // Set PWM mode and enable timer outputs
    TIM16->CCMR1 &= ~(0b111 << 4);  // Clear Output Compare 1 mode
    TIM16->CCMR1 |= (0b110 << 4);   // 0110: PWM mode 1 - Channel 1 is active as long as TIMx_CNT<TIMx_CCR1 else inactive
    TIM16->CCMR1 |= (1 << 3);       // Enable preload
    TIM16->CCMR1 &= ~(0b11 << 0);   // 00: CC1 channel is configured as output

    TIM16->CR1 |= (1 << 7);         // 1: TIMx_ARR register is buffered
    TIM16->CCER |= (1 << 0);        // Enable CC1 output 
    TIM16->BDTR |= (1 << 15);       // Enable Main output 

    // Update Timer and Enable
    TIM16->EGR = (1 << 0);      // Load new values into counter
    TIM16->CR1 |= (1 << 0);     // Enable the counter
    
    while (1) {	
        for (int i = 0; (notes[i][0] != 0 || notes[i][1] != 0); i++) {
          uint32_t freq = notes[i][0];
          uint32_t dur  = notes[i][1];
          play_note(freq,dur);
        }
    }

}
